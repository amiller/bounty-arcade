import { test, expect } from '@playwright/test'
const position = page => page.locator('#board .cell').evaluateAll(cells => cells.map(c => c.className))
test('solution link selects its level and sharing preserves the complete solved position', async ({ page, context }) => {
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/apps/puzzle/#level=2&moves=lLLLrrrddLLL')
  await expect(page.getByTestId('level')).toHaveValue('2')
  await expect(page.getByTestId('moves')).toHaveText('12')
  await expect(page.getByTestId('status')).toContainText('Solved')
  const expected = await position(page)
  await page.getByTestId('share').click()
  await expect(page.locator('#share-url')).toHaveAttribute('readonly', '')
  const url = await page.locator('#share-url').inputValue()
  expect(new URL(url).hash).toBe('#level=2&moves=lLLLrrrddLLL')
  const opened = await context.newPage()
  await opened.goto(url)
  await expect(opened.getByTestId('moves')).toHaveText('12')
  await expect(opened.getByTestId('status')).toContainText('Solved')
  expect(await position(opened)).toEqual(expected)
  await opened.close()
  expect(errors).toEqual([])
})
test('a blocked third step preserves only its prefix; undo, sharing and restart use current history', async ({ page, context }) => {
  await page.goto('/apps/puzzle/#level=0&moves=rRurR')
  await expect(page.getByTestId('moves')).toHaveText('2')
  await expect(page.getByTestId('pushes')).toHaveText('1')
  await expect(page.getByTestId('status')).toContainText('blocked at step 3')
  await page.getByTestId('share').click()
  expect(new URL(await page.locator('#share-url').inputValue()).hash).toBe('#level=0&moves=rR')
  await page.getByTestId('undo').click()
  await expect(page.getByTestId('moves')).toHaveText('1')
  await expect(page.getByTestId('status')).toHaveText('')
  const expected = await position(page)
  await page.getByTestId('share').click()
  const url = await page.locator('#share-url').inputValue()
  expect(new URL(url).hash).toBe('#level=0&moves=r')
  const opened = await context.newPage()
  await opened.goto(url)
  await expect(opened.getByTestId('moves')).toHaveText('1')
  expect(await position(opened)).toEqual(expected)
  await opened.close()
  await page.getByTestId('restart').click()
  await expect(page.getByTestId('moves')).toHaveText('0')
  await page.getByTestId('share').click()
  expect(new URL(await page.locator('#share-url').inputValue()).hash).toBe('#level=0&moves=')
})
test('out-of-range replay fails visibly and keyboard play produces a new usable link', async ({ page, context }) => {
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/apps/puzzle/#level=999&moves=r')
  await expect(page.getByTestId('status')).toContainText('level does not exist')
  await expect(page.getByTestId('moves')).toHaveText('0')
  await page.keyboard.press('ArrowRight')
  await page.keyboard.press('ArrowRight')
  await expect(page.getByTestId('moves')).toHaveText('2')
  await page.getByTestId('share').click()
  const url = await page.locator('#share-url').inputValue()
  expect(new URL(url).hash).toBe('#level=0&moves=rR')
  await page.locator('#share-url').focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByTestId('moves')).toHaveText('2')
  const opened = await context.newPage()
  await opened.goto(url)
  await expect(opened.getByTestId('moves')).toHaveText('2')
  await expect(opened.getByTestId('pushes')).toHaveText('1')
  await opened.close()
  expect(errors).toEqual([])
})
