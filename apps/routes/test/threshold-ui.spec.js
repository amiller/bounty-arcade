import { test, expect } from '@playwright/test'
test('threshold filters the current sample immediately and zero restores raw stats without redrawing', async ({ page }) => {
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/apps/routes/')
  await expect(page.getByTestId('stat-gain')).toHaveText('865 m')
  await expect(page.getByTestId('threshold')).toHaveValue('0')
  await page.getByTestId('sample').selectOption('samples/riverside-loop.gpx')
  await expect(page.getByTestId('stat-gain')).toHaveText('53 m')
  const track = await page.locator('#track').innerHTML()
  const profile = await page.locator('#profile').innerHTML()
  const rawLoss = await page.getByTestId('stat-loss').textContent()
  await page.getByTestId('threshold').fill('1')
  await expect.poll(async () => parseFloat(await page.getByTestId('stat-gain').textContent())).toBeLessThan(50)
  await expect.poll(async () => parseFloat(await page.getByTestId('stat-loss').textContent())).toBeLessThan(parseFloat(rawLoss))
  await expect(page.getByTestId('stat-distance')).toHaveText('9.11 km')
  await expect(page.getByTestId('stat-count')).toHaveText('301')
  expect(await page.locator('#track').innerHTML()).toBe(track)
  expect(await page.locator('#profile').innerHTML()).toBe(profile)
  await page.getByTestId('threshold').fill('0')
  await expect(page.getByTestId('stat-gain')).toHaveText('53 m')
  await expect(page.getByTestId('stat-loss')).toHaveText(rawLoss)
  expect(errors).toEqual([])
})
test('selected threshold applies to uploaded GPX; invalid values preserve stats and clearing restores raw', async ({ page }) => {
  await page.goto('/apps/routes/')
  await expect(page.getByTestId('stat-gain')).toHaveText('865 m')
  await page.getByTestId('threshold').fill('2')
  const points = [100, 101, 100, 105, 104, 110].map((ele, i) =>
    '<trkpt lat="0" lon="' + i / 1000 + '"><ele>' + ele + '</ele></trkpt>').join('')
  await page.getByTestId('file').setInputFiles({ name: 'hysteresis.gpx', mimeType: 'application/gpx+xml',
    buffer: Buffer.from('<gpx><trk><trkseg>' + points + '</trkseg></trk></gpx>') })
  await expect(page.locator('#route-name')).toHaveText('hysteresis')
  await expect(page.getByTestId('stat-gain')).toHaveText('10 m')
  await expect(page.getByTestId('stat-loss')).toHaveText('0 m')
  await page.getByTestId('threshold').fill('-1')
  expect(await page.getByTestId('threshold').evaluate(el => el.checkValidity())).toBe(false)
  await expect(page.getByTestId('stat-gain')).toHaveText('10 m')
  await page.getByTestId('threshold').fill('')
  await expect(page.getByTestId('stat-gain')).toHaveText('12 m')
  await expect(page.getByTestId('stat-loss')).toHaveText('2 m')
  expect(await page.getByTestId('threshold').evaluate(el => el.checkValidity())).toBe(true)
  await page.getByTestId('threshold').fill('2')
  await expect(page.getByTestId('stat-gain')).toHaveText('10 m')
  await page.getByTestId('sample').selectOption('samples/riverside-loop.gpx')
  await expect(page.locator('#route-name')).toHaveText('Riverside Loop')
  await expect.poll(async () => parseFloat(await page.getByTestId('stat-gain').textContent())).toBeLessThan(50)
})
