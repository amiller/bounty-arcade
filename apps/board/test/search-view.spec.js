import { test, expect } from '@playwright/test'

async function open(page) {
  await page.goto('/apps/board/')
  await expect(page.getByTestId('board')).toHaveAttribute('data-ready', 'true')
}
async function add(page, column, text, saved) {
  await page.getByTestId('new-' + column).fill(text)
  await page.getByTestId('add-' + column).click()
  await expect(page.getByTestId('board')).toHaveAttribute('data-saved', String(saved))
}
const count = (page, column) => page.getByTestId('column-' + column).locator('h2 span')
const visible = page => page.locator('[data-testid=card]:visible')

test('mixed-case search covers all columns, blank queries clear counts, reload resets only the view', async ({ page }) => {
  await open(page)
  await add(page, 'todo', 'Alpha', 1)
  await add(page, 'todo', 'beta', 2)
  await add(page, 'doing', 'ALPHABET', 3)
  await add(page, 'done', 'Finished alpha', 4)
  const search = page.getByTestId('search')
  await search.fill('aLp')
  await expect(visible(page)).toHaveCount(3)
  await expect(count(page, 'todo')).toHaveText('1/2')
  await expect(count(page, 'doing')).toHaveText('1/1')
  await expect(count(page, 'done')).toHaveText('1/1')
  await expect(page.getByTestId('board')).toHaveAttribute('data-saved', '4')
  await search.fill('not found')
  await expect(visible(page)).toHaveCount(0)
  await expect(count(page, 'todo')).toHaveText('0/2')
  for (const query of ['', '   ']) {
    await search.fill(query)
    await expect(visible(page)).toHaveCount(4)
    await expect(count(page, 'todo')).toHaveText('2')
  }
  await search.fill('alp')
  await page.reload()
  await expect(page.getByTestId('board')).toHaveAttribute('data-ready', 'true')
  await expect(search).toHaveValue('')
  await expect(visible(page)).toHaveCount(4)
  await expect(count(page, 'todo')).toHaveText('2')
})

test('adding, moving and editing while filtered updates matches and exports every card', async ({ page }) => {
  await open(page)
  await add(page, 'todo', 'Hidden beta', 1)
  await add(page, 'todo', 'Alpha', 2)
  await page.getByTestId('search').fill('alp')
  await add(page, 'todo', 'Other hidden', 3)
  await add(page, 'done', 'alpha docs', 4)
  await expect(visible(page)).toHaveCount(2)
  await expect(count(page, 'todo')).toHaveText('1/3')
  const alpha = page.getByTestId('column-todo').getByTestId('card')
  await alpha.locator('[data-action=right]').click()
  await expect(page.getByTestId('board')).toHaveAttribute('data-saved', '5')
  await expect(count(page, 'todo')).toHaveText('0/2')
  await expect(count(page, 'doing')).toHaveText('1/1')
  await page.getByTestId('column-doing').locator('[data-action=edit]').click()
  await page.getByTestId('edit-input').fill('Renamed away')
  await page.getByTestId('edit-input').press('Enter')
  await expect(page.getByTestId('board')).toHaveAttribute('data-saved', '6')
  await expect(count(page, 'doing')).toHaveText('0/1')
  await expect(visible(page)).toHaveCount(1)
  const downloaded = page.waitForEvent('download')
  await page.getByTestId('export').click()
  const stream = await (await downloaded).createReadStream()
  const chunks = []
  for await (const chunk of stream) chunks.push(chunk)
  const exported = JSON.parse(Buffer.concat(chunks).toString('utf8'))
  expect(exported.columns.todo.map(c => c.text)).toEqual(['Hidden beta', 'Other hidden'])
  expect(exported.columns.doing.map(c => c.text)).toEqual(['Renamed away'])
  expect(exported.columns.done.map(c => c.text)).toEqual(['alpha docs'])
  expect(Object.keys(exported).sort()).toEqual(['columns', 'nextId'])
  await page.reload()
  await expect(page.getByTestId('board')).toHaveAttribute('data-ready', 'true')
  await expect(visible(page)).toHaveCount(4)
  await expect(page.getByTestId('search')).toHaveValue('')
})

test('filtered reorder uses original positions including hidden cards', async ({ page }) => {
  await open(page)
  await add(page, 'todo', 'Hidden first', 1)
  await add(page, 'todo', 'alpha middle', 2)
  await add(page, 'todo', 'Hidden last', 3)
  await page.getByTestId('search').fill('alpha')
  await page.getByTestId('column-todo').locator('[data-action=up]').click()
  await expect(page.getByTestId('board')).toHaveAttribute('data-saved', '4')
  await page.getByTestId('search').fill('')
  await expect(page.getByTestId('column-todo').locator('.card p')).toHaveText(['alpha middle', 'Hidden first', 'Hidden last'])
})
