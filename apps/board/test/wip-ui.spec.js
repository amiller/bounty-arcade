import { test, expect } from '@playwright/test'
const cards = (page, col) => page.getByTestId('column-' + col).getByTestId('card')
async function start(page) {
  await page.goto('/apps/board/')
  await expect(page.getByTestId('board')).toHaveAttribute('data-ready', 'true')
}
async function add(page, col, text) {
  await page.getByTestId('new-' + col).fill(text)
  await page.getByTestId('add-' + col).click()
}
async function exported(page) {
  const download = page.waitForEvent('download')
  await page.getByTestId('export').click()
  const stream = await (await download).createReadStream()
  let text = ''
  for await (const chunk of stream) text += chunk.toString()
  return JSON.parse(text)
}
test('full Doing disables incoming controls, survives reload, and clearing restores legacy export', async ({ page }) => {
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await start(page)
  await page.getByTestId('limit-doing').fill('1')
  await add(page, 'todo', 'incoming')
  await add(page, 'done', 'returning')
  await add(page, 'doing', 'working')
  await expect(page.getByTestId('board')).toHaveAttribute('data-saved', '4')
  for (const id of ['new-doing', 'add-doing']) await expect(page.getByTestId(id)).toBeDisabled()
  await expect(cards(page, 'todo').locator('[data-action=right]')).toBeDisabled()
  await expect(cards(page, 'done').locator('[data-action=left]')).toBeDisabled()
  await page.reload()
  await expect(page.getByTestId('limit-doing')).toHaveValue('1')
  await expect(page.getByTestId('add-doing')).toBeDisabled()
  expect((await exported(page)).limits).toEqual({ doing: 1 })
  await page.getByTestId('limit-doing').fill('')
  await expect(page.getByTestId('board')).toHaveAttribute('data-saved', '1')
  await expect(page.getByTestId('new-doing')).toBeEnabled()
  await expect(cards(page, 'todo').locator('[data-action=right]')).toBeEnabled()
  await expect(cards(page, 'done').locator('[data-action=left]')).toBeEnabled()
  expect(await exported(page)).not.toHaveProperty('limits')
  await page.reload()
  await expect(page.getByTestId('limit-doing')).toHaveValue('')
  expect(errors).toEqual([])
})
test('full-column reordering and outgoing moves work; rejected limits and drops do not save', async ({ page }) => {
  await start(page)
  await add(page, 'doing', 'first')
  await add(page, 'doing', 'second')
  await add(page, 'todo', 'third')
  await page.getByTestId('limit-doing').fill('2')
  await cards(page, 'doing').last().locator('[data-action=up]').click()
  await expect(cards(page, 'doing').first().locator('p')).toHaveText('second')
  await expect(page.getByTestId('board')).toHaveAttribute('data-saved', '5')
  await page.getByTestId('limit-doing').fill('1')
  await expect(page.locator('#status')).toContainText('WIP limit')
  await expect(page.getByTestId('limit-doing')).toHaveValue('2')
  const transfer = await page.evaluateHandle(() => { const d = new DataTransfer(); d.setData('text/plain', 'c3'); return d })
  await page.getByTestId('column-doing').dispatchEvent('drop', { dataTransfer: transfer })
  await expect(page.locator('#status')).toContainText('WIP limit')
  await expect(cards(page, 'doing')).toHaveCount(2)
  await expect(page.getByTestId('board')).toHaveAttribute('data-saved', '5')
  await cards(page, 'doing').first().locator('[data-action=right]').click()
  await expect(page.getByTestId('add-doing')).toBeEnabled()
  await cards(page, 'todo').locator('[data-action=right]').click()
  await expect(cards(page, 'doing')).toHaveCount(2)
  await expect(page.getByTestId('board')).toHaveAttribute('data-saved', '7')
})
test('JSON import retains limits and rejects overfull data without replacing persisted board', async ({ page }) => {
  await start(page)
  const board = { nextId: 2, columns: { todo: [], doing: [{ id: 'c1', text: 'imported' }], done: [] }, limits: { doing: 1 } }
  const upload = b => page.locator('#import').setInputFiles({ name: 'board.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(b)) })
  await upload(board)
  await expect(page.getByTestId('board')).toHaveAttribute('data-saved', '1')
  await expect(page.getByTestId('add-doing')).toBeDisabled()
  expect(await exported(page)).toEqual(board)
  await upload({ ...board, nextId: 3, columns: { ...board.columns, doing: [...board.columns.doing, { id: 'c2', text: 'excess' }] } })
  await expect(page.locator('#status')).toContainText('invalid board')
  await expect(page.getByTestId('board')).toHaveAttribute('data-saved', '1')
  expect(await exported(page)).toEqual(board)
  await page.reload()
  await expect(cards(page, 'doing')).toHaveCount(1)
  await expect(page.getByTestId('limit-doing')).toHaveValue('1')
})
