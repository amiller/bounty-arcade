import { test, expect } from '@playwright/test'

test('history controls, edits, deletion, keyboard branches and persisted undo', async ({ page }) => {
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/apps/board/')
  const board = page.getByTestId('board')
  const undo = page.getByTestId('undo'), redo = page.getByTestId('redo')
  const cards = page.getByTestId('column-todo').getByTestId('card')
  await expect(board).toHaveAttribute('data-ready', 'true')
  await expect(undo).toBeDisabled()
  await expect(redo).toBeDisabled()
  await page.getByTestId('new-todo').fill('alpha')
  await page.getByTestId('add-todo').click()
  await cards.locator('[data-action=edit]').click()
  await page.getByTestId('edit-input').fill('beta')
  await page.getByTestId('edit-input').press('Enter')
  await cards.locator('[data-action=delete]').click()
  await expect(cards).toHaveCount(0)
  await undo.click()
  await expect(cards).toHaveText(/beta/)
  await page.keyboard.press('Meta+z')
  await expect(cards).toHaveText(/alpha/)
  await page.keyboard.press('Meta+Shift+z')
  await expect(cards).toHaveText(/beta/)
  await expect(board).toHaveAttribute('data-saved', '6')

  // Adding a card after undo discards the deleted-card redo branch.
  await page.getByTestId('new-todo').fill('gamma')
  await page.getByTestId('add-todo').click()
  await expect(redo).toBeDisabled()
  await undo.click()
  await expect(board).toHaveAttribute('data-saved', '8')
  await page.reload()
  await expect(board).toHaveAttribute('data-ready', 'true')
  await expect(cards).toHaveCount(1)
  await expect(cards).toHaveText(/beta/)
  await expect(undo).toBeDisabled()
  await expect(redo).toBeDisabled()
  expect(errors).toEqual([])
})

test('import resets both directions; invalid import and text shortcuts preserve history', async ({ page }) => {
  await page.goto('/apps/board/')
  const board = page.getByTestId('board')
  await expect(board).toHaveAttribute('data-ready', 'true')
  await page.getByTestId('new-todo').fill('alpha')
  await page.getByTestId('add-todo').click()
  const input = page.getByTestId('new-todo')
  await input.fill('draft')
  await input.press('Control+z')
  await expect(page.getByTestId('column-todo').getByTestId('card')).toHaveCount(1)
  await expect(board).toHaveAttribute('data-saved', '1')
  const upload = content => page.getByTestId('import').setInputFiles({
    name: 'board.json', mimeType: 'application/json', buffer: Buffer.from(content),
  })
  await upload('{}')
  await expect(page.getByTestId('status')).toContainText('Import failed')
  await expect(page.getByTestId('undo')).toBeEnabled()
  await page.getByTestId('undo').click()
  await expect(page.getByTestId('redo')).toBeEnabled()
  await upload(JSON.stringify({ nextId: 2, columns: { todo: [], doing: [{ id: 'c1', text: 'imported' }], done: [] } }))
  await expect(board).toHaveAttribute('data-saved', '3')
  await expect(page.getByTestId('undo')).toBeDisabled()
  await expect(page.getByTestId('redo')).toBeDisabled()
  await page.reload()
  await expect(board).toHaveAttribute('data-ready', 'true')
  await expect(page.getByTestId('column-doing').getByTestId('card')).toHaveText(/imported/)
  await expect(page.getByTestId('undo')).toBeDisabled()
})
